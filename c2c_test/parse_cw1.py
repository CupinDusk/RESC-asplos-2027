# Parse CW1 sweep cell logs -> CW1_RESULTS.txt with every raw number + ratio tables.
import os, re, glob

RUNS = "/legacy-research/owner/cudatest/RESC-c2c-wt/c2c_test/cw1_runs"
OUT  = "/legacy-research/owner/cudatest/RESC-c2c-wt/c2c_test/CW1_RESULTS.txt"

def grab(txt, pat, cast=int, default=None):
    m = re.search(pat, txt)
    if not m: return default
    try: return cast(m.group(1))
    except: return default

def parse_cell(d):
    log = os.path.join(d, "run.log")
    if not os.path.exists(log): return None
    txt = open(log, errors="replace").read()
    r = {}
    r["cell"] = os.path.basename(d)
    # PIPE_CHAIN line
    m = re.search(r"PIPE_CHAIN cluster=(\d+) num_clusters=(\d+) nstages=(\d+) lag=(\d+) tile_lines=(\d+) OUT_CHECKSUM=(\d+) REF_CHECKSUM=(\d+) BITIDENTICAL=(\d+)", txt)
    if m:
        r["cluster"], r["num_clusters"], r["nstages"], r["lag"], r["tile_lines"] = (int(m.group(i)) for i in range(1,6))
        r["out_checksum"], r["ref_checksum"], r["bitidentical"] = int(m.group(6)), int(m.group(7)), int(m.group(8))
    r["gpu_tot_sim_cycle"] = grab(txt, r"gpu_tot_sim_cycle = (\d+)")
    # RESC_GEN_STATS
    m = re.search(r"\[RESC_GEN_STATS\] gen_ring=(-?\d+) epoch_ticks=(\d+) readshare_served=(\d+) readshare_expired=(\d+)", txt)
    if m:
        r["gen_ring"], r["epoch_ticks"], r["served"], r["expired"] = (int(m.group(i)) for i in range(1,5))
    # L2 aggregate
    r["L2_accesses"] = grab(txt, r"L2_total_cache_accesses = (\d+)")
    r["L2_misses"]   = grab(txt, r"L2_total_cache_misses = (\d+)")
    r["L2_miss_rate"]= grab(txt, r"L2_total_cache_miss_rate = ([\d.]+)", float)
    r["L2_resv_fails"]=grab(txt, r"L2_total_cache_reservation_fails = (\d+)")
    m = re.search(r"L2_BW_total\s*=\s*([\d.]+)", txt);  r["L2_BW_total"] = float(m.group(1)) if m else None
    # DRAM
    r["dram_reads"]  = grab(txt, r"total dram reads = (\d+)")
    r["dram_writes"] = grab(txt, r"total dram writes = (\d+)")
    r["gpu_stall_dramfull"] = grab(txt, r"gpu_stall_dramfull = (\d+)")
    r["gpu_stall_icnt2sh"]  = grab(txt, r"gpu_stall_icnt2sh\s*=\s*(\d+)")
    # latencies
    r["averagemflatency"]      = grab(txt, r"averagemflatency = (\d+)")
    r["avg_icnt2mem_latency"]  = grab(txt, r"avg_icnt2mem_latency = (\d+)")
    r["max_icnt2mem_latency"]  = grab(txt, r"max_icnt2mem_latency = (\d+)")
    r["gl_coal_stall"] = grab(txt, r"gpgpu_stall_shd_mem\[gl_mem\]\[coal_stall\] = (\d+)")
    r["gl_data_port_stall"] = grab(txt, r"gpgpu_stall_shd_mem\[gl_mem\]\[data_port_stall\] = (\d+)")
    # L2 GLOBAL_ACC_R hit/miss breakdown
    r["L2_R_HIT"]  = grab(txt, r"L2_cache_stats_breakdown\[GLOBAL_ACC_R\]\[HIT\] = (\d+)")
    r["L2_R_MISS"] = grab(txt, r"L2_cache_stats_breakdown\[GLOBAL_ACC_R\]\[MISS\] = (\d+)")
    return r

def key(cell):
    m = re.match(r"(h1_nc(\d+)|h2_tl(\d+))_ring(\d+)", cell)
    return m

cells = {}
for d in sorted(glob.glob(os.path.join(RUNS, "*"))):
    if not os.path.isdir(d): continue
    r = parse_cell(d)
    if r: cells[r["cell"]] = r

lines = []
lines.append("=== CW1 RESULTS (pre-registered ring-vs-DeNovo sweep) ===")
lines.append("Generated by parse_cw1.py. Every raw number per cell below.\n")

# Full dump
flds = ["gen_ring","num_clusters","nstages","lag","tile_lines","gpu_tot_sim_cycle",
        "served","expired","epoch_ticks","bitidentical","out_checksum","ref_checksum",
        "L2_accesses","L2_misses","L2_miss_rate","L2_resv_fails","L2_BW_total",
        "L2_R_HIT","L2_R_MISS","dram_reads","dram_writes","gpu_stall_dramfull",
        "averagemflatency","avg_icnt2mem_latency","max_icnt2mem_latency",
        "gl_coal_stall","gl_data_port_stall"]
for name in sorted(cells):
    r = cells[name]
    lines.append(f"---- {name} ----")
    for f in flds:
        lines.append(f"    {f} = {r.get(f)}")
    lines.append("")

def ratio_table(title, cellnames, axis_label, axis_vals):
    lines.append(f"=== {title} ===")
    lines.append(f"{axis_label:>10} | arm0_cyc  arm2_cyc  arm3_cyc | arm3/arm2 | served2 served3 | bitid2 bitid3 | L2mr2  L2mr3 | mflat2 mflat3")
    for v, (c0,c2,c3) in zip(axis_vals, cellnames):
        r0,r2,r3 = cells.get(c0,{}), cells.get(c2,{}), cells.get(c3,{})
        cyc0,cyc2,cyc3 = r0.get("gpu_tot_sim_cycle"),r2.get("gpu_tot_sim_cycle"),r3.get("gpu_tot_sim_cycle")
        rat = (cyc3/cyc2) if (cyc2 and cyc3) else None
        rat_s = f"{rat:.4f}" if rat else "NA"
        lines.append(f"{v:>10} | {str(cyc0):>8} {str(cyc2):>8} {str(cyc3):>8} | {rat_s:>9} | "
                     f"{str(r2.get('served')):>7} {str(r3.get('served')):>7} | "
                     f"{str(r2.get('bitidentical')):>6} {str(r3.get('bitidentical')):>6} | "
                     f"{str(r2.get('L2_miss_rate')):>5} {str(r3.get('L2_miss_rate')):>5} | "
                     f"{str(r2.get('averagemflatency')):>6} {str(r3.get('averagemflatency')):>6}")
    lines.append("")

# H1
h1 = [4,16,64,128,256]
h1_cells = [(f"h1_nc{n}_ring1",f"h1_nc{n}_ring2",f"h1_nc{n}_ring3") for n in h1]
ratio_table("H1 concurrency sweep (nstages=32 tile_lines=4 lag=2)", h1_cells, "num_clust", h1)

# H2 : tl=4 reuses h1_nc64
h2 = [4,16,64,256]
h2_cells = []
for t in h2:
    if t==4:
        h2_cells.append(("h1_nc64_ring1","h1_nc64_ring2","h1_nc64_ring3"))
    else:
        h2_cells.append((f"h2_tl{t}_ring1",f"h2_tl{t}_ring2",f"h2_tl{t}_ring3"))
ratio_table("H2 capacity sweep (num_clusters=64 nstages=32 lag=2)", h2_cells, "tile_line", h2)

open(OUT,"w").write("\n".join(lines))
print(f"WROTE {OUT}")
print("\n".join(lines[-40:]))
